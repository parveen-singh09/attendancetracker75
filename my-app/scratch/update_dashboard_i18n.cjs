for (const [lang, dict] of Object.entries(translations)) {
  const marker = new RegExp(`const\\s+${lang}:\\s*Dict\\s*=\\s*\\{`);
  const match = content.match(marker);
  if (!match) {
    console.error(`Could not find declaration of dictionary: ${lang}`);
    process.exit(1);
  }
  const startIndex = match.index + match[0].length;
  
  // Find the closing brace of the dictionary
  let braceIndex = content.indexOf('};', startIndex);
  if (braceIndex === -1) {
    console.error(`Could not find end of dictionary: ${lang}`);
    process.exit(1);
  }
  
  // Build the text to insert
  let insertion = '\n';
  for (const [k, v] of Object.entries(dict)) {
    const escapedVal = v.replace(/'/g, "\\'").replace(/\n/g, '\\n');
    insertion += `  '${k}': '${escapedVal}',\n`;
  }
  
  content = content.slice(0, braceIndex) + insertion + content.slice(braceIndex);
}

fs.writeFileSync(targetFile, content, 'utf8');
